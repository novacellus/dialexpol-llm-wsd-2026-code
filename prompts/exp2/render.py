#!/usr/bin/env python3
"""
Render Experiment 2 prompt templates.

Same shape as prompts/exp1/render.py — reads components.yaml + conditions.yaml
and writes flat .txt files into rendered/. The two render scripts are
deliberately separate so changes to Exp 1's block library never silently
shift Exp 2's prompts (the experiments share a sense-inventory block but
not the input-presentation blocks).

Usage:
  python prompts/exp2/render.py            # (re)render all templates
  python prompts/exp2/render.py --check    # verify rendered/ is current
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).parent
REPO = HERE.parent.parent                      # 2026/ai/
COMPONENTS = HERE / "components.yaml"
CONDITIONS = HERE / "conditions.yaml"
OUT_DIR = HERE / "rendered"


def generated_header(name: str) -> str:
    """Single-line Nunjucks comment; promptfoo's loader needs single-line."""
    return (
        f"{{# GENERATED by prompts/exp2/render.py from components.yaml + "
        f"conditions.yaml — DO NOT EDIT; template: {name} #}}"
    )


def render_block(block_name: str, blocks: dict) -> str:
    block = blocks[block_name]
    text = block["text"].rstrip("\n")
    guard = block.get("guard")
    if guard:
        return f"{{% if {guard} %}}\n{text}\n{{% endif %}}"
    return text


def render_template(name: str, spec: dict, blocks: dict) -> str:
    parts = [generated_header(name)]
    for block_name in spec["blocks"]:
        if block_name not in blocks:
            sys.exit(
                f"ERROR: template '{name}' references unknown block "
                f"'{block_name}' (not in components.yaml)"
            )
        parts.append(render_block(block_name, blocks))
    return "\n\n".join(parts) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify rendered/ matches the spec; exit 1 if stale")
    args = ap.parse_args()

    components = yaml.safe_load(COMPONENTS.read_text(encoding="utf-8"))
    conditions = yaml.safe_load(CONDITIONS.read_text(encoding="utf-8"))
    blocks = components["blocks"]
    templates = conditions["templates"]

    OUT_DIR.mkdir(exist_ok=True)

    stale: list[str] = []
    for name, spec in templates.items():
        rendered = render_template(name, spec, blocks)
        path = OUT_DIR / f"{name}.txt"
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != rendered:
                stale.append(name)
        else:
            path.write_text(rendered, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")

    if args.check:
        if stale:
            sys.exit(f"STALE — re-run render.py: {', '.join(stale)}")
        print("rendered/ is up to date")
        return

    print(f"\n{len(templates)} templates rendered to {OUT_DIR.relative_to(REPO)}/")


if __name__ == "__main__":
    main()
