#!/usr/bin/env python3
"""
Render Experiment 1 prompt templates.

Reads the declarative component spec and composes the flat .txt prompts that
promptfoo consumes.

  components.yaml  — reusable blocks of prompt text
  conditions.yaml  — which blocks compose each template
        |
        v   render.py
  rendered/*.txt   — GENERATED; promptfoo reads these; do NOT hand-edit

Two templating levels are kept separate (see README.md):
  build-time (this script) — which blocks go into each template
  run-time   (promptfoo)   — {{placeholders}} and {% if %} guards, per test case

A block with a `guard:` key is wrapped in a Nunjucks `{% if guard %}` so the
run-time variable (e.g. show_metadata) toggles it without a separate file.

Usage:
  python prompts/exp1/render.py            # (re)render all templates
  python prompts/exp1/render.py --check    # verify rendered/ is current; exit 1 if stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).parent
REPO = HERE.parent.parent                      # 2026/ai/
COMPONENTS = HERE / "components.yaml"
CONDITIONS = HERE / "conditions.yaml"
OUT_DIR = HERE / "rendered"


def generated_header(name: str) -> str:
    """Single-line Nunjucks comment ({# #}) — provenance, stripped before the
    model sees it.

    MUST stay single-line: promptfoo's prompt loader does not treat a file as a
    Nunjucks template if it opens with a *multi-line* {# #} comment (the
    `{{vars}}` then render literally). A single-line comment is fine.
    """
    return (
        f"{{# GENERATED by prompts/exp1/render.py from components.yaml + "
        f"conditions.yaml — DO NOT EDIT; template: {name} #}}"
    )


def render_block(block_name: str, blocks: dict) -> str:
    """Return one block's text, wrapped in a Nunjucks guard if it has one."""
    block = blocks[block_name]
    text = block["text"].rstrip("\n")
    guard = block.get("guard")
    if guard:
        return f"{{% if {guard} %}}\n{text}\n{{% endif %}}"
    return text


def render_template(name: str, spec: dict, blocks: dict) -> str:
    """Compose a template from its ordered block list."""
    parts = [generated_header(name)]
    for block_name in spec["blocks"]:
        if block_name not in blocks:
            sys.exit(
                f"ERROR: template '{name}' references unknown block "
                f"'{block_name}' (not in components.yaml)"
            )
        parts.append(render_block(block_name, blocks))
    return "\n\n".join(parts) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check", action="store_true",
        help="verify rendered/ matches the spec; exit 1 if anything is stale",
    )
    args = ap.parse_args()

    components = yaml.safe_load(COMPONENTS.read_text(encoding="utf-8"))
    conditions = yaml.safe_load(CONDITIONS.read_text(encoding="utf-8"))
    blocks = components["blocks"]
    templates = conditions["templates"]

    OUT_DIR.mkdir(exist_ok=True)

    stale: list[str] = []
    for name, spec in templates.items():
        rendered = render_template(name, spec, blocks)
        path = OUT_DIR / f"{name}.txt"
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != rendered:
                stale.append(name)
        else:
            path.write_text(rendered, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")

    if args.check:
        if stale:
            sys.exit(f"STALE — re-run render.py: {', '.join(stale)}")
        print("rendered/ is up to date")
        return

    print(f"\n{len(templates)} templates rendered to {OUT_DIR.relative_to(REPO)}/")


if __name__ == "__main__":
    main()
